@router.get("")
def list_faq(category: str | None = Query(default=None, description="分类 id，缺省返回全部分类")):
    """FAQ 分类浏览：返回分类列表 + 问答（按 category 过滤）"""
    categories = [
        {"id": c["id"], "name": c["name"], "icon": c["icon"], "count": len(c["questions"])}
        for c in FAQ_CATEGORIES
    ]
    if category:
        matched = next((c for c in FAQ_CATEGORIES if c["id"] == category), None)
        if matched is None:
            return {"categories": categories, "questions": [], "demo": True}
        return {"categories": categories, "questions": matched["questions"], "demo": True}
    all_questions = [
        {"category": c["name"], **q} for c in FAQ_CATEGORIES for q in c["questions"]
    ]
    return {"categories": categories, "questions": all_questions, "demo": True}
